"""Annotation-aware circular plasmid references and MCS cut schemes.

The committed JSON generated by this module is the authority used by the v2
designer.  Raw SnapGene files are deliberately not committed: they are parsed
in a temporary directory and reduced to sequence hashes and normalized feature
intervals.  Coordinates in the public models are zero-based, half-open.
"""

