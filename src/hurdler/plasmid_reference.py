@dataclass(frozen=True)
class PlasmidSource:
    provider: str
    accession: str
    url: str
    downloaded_at: str
    sha256: str


@dataclass(frozen=True)
class PlasmidFeature:
    feature_id: str
    feature_type: str
    label: str
    intervals: tuple[tuple[int, int], ...]
    strand: int
    sources: tuple[str, ...]
    protected: bool
    feature_class: str

    @property
    def start(self) -> int:
        return min(value[0] for value in self.intervals)

    @property
    def end(self) -> int:
        return max(value[1] for value in self.intervals)


@dataclass(frozen=True)
class PlasmidReference:
    reference_id: str
    display_name: str
    sequence: str
    sequence_sha256: str
    circular: bool
    features: tuple[PlasmidFeature, ...]
    sources: tuple[PlasmidSource, ...]


@dataclass(frozen=True)
class PlasmidProfile:
    profile_id: str
    reference_id: str
    expression_strand: int
    mcs_start: int
    mcs_end: int
    legacy_left_enzyme: str
    legacy_right_enzyme: str
    notes: str = ""


@dataclass(frozen=True)
class CutterSite:
    side: str
    location: str
    canonical_enzyme: str
    enzyme_aliases: tuple[str, ...]
    recognition_site: str
    oriented_start: int
    oriented_end: int
    physical_start: int
    physical_end: int
    top_cut_oriented: int
    bottom_cut_oriented: int
    overhang_length: int
    outside_mcs_occurrences: int


@dataclass(frozen=True)
class VectorCutScheme:
    scheme_id: str
    profile_id: str
    left_location: str
    right_location: str
    left_cutter: CutterSite | None
    right_cutter: CutterSite | None
    valid: bool
    invalid_reason: str
    retained_backbone_sequence: str
    removed_arc_sequence: str
    left_restoration_sequence: str
    right_restoration_sequence: str
    retained_backbone_sha256: str


@dataclass(frozen=True)
class SilencingDecision:
    side: str
    allowed: bool
    status: str
    reason: str
    overlapping_features: tuple[str, ...] = ()
    donor_only_required: bool = True
    stop_rescue_sequence: str = ""


@dataclass(frozen=True)
class PlasmidReferenceDatabase:
    schema_version: str
    generated_at: str
    references: tuple[PlasmidReference, ...]
    profiles: tuple[PlasmidProfile, ...]
    schemes: tuple[VectorCutScheme, ...]

    def reference(self, reference_id: str) -> PlasmidReference:
        return next(item for item in self.references if item.reference_id == reference_id)

    def profile(self, profile_id: str) -> PlasmidProfile:
        return next(item for item in self.profiles if item.profile_id == profile_id)

    def schemes_for(self, profile_id: str) -> tuple[VectorCutScheme, ...]:
        return tuple(item for item in self.schemes if item.profile_id == profile_id)


